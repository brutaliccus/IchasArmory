/**
 * Get all available raids
 * @returns {Array} Array of raid names
 */
export function getAvailableRaids() {
    return Object.keys(raidDefinitions);
}

/**
 * Get boss list for a raid
 * @param {string} raidName - Name of the raid
 * @returns {Array|null} Array of boss objects with npcId and name, or null if raid not found
 */
export function getRaidBosses(raidName) {
    const raid = raidDefinitions[raidName];
    return raid ? raid.bosses : null;
}

